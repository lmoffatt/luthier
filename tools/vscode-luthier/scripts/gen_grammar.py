#!/usr/bin/env python3
"""Generate TextMate syntax (v1; deterministic, no seed; mode is the only parameter)."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / 'src'))
from luthier.ebnf import GRAMMAR_LTH, cats_of, lits_of, lits_of_names, luthier_syntax
from luthier.check import coreNames

OUTPUT = Path(__file__).resolve().parents[1] / 'syntaxes/luthier.tmLanguage.json'
NAME = r"[A-Za-z][A-Za-z0-9_']*(?:\.[A-Za-z][A-Za-z0-9_']*)*"
EDGE = r"[A-Za-z0-9_'.]"


def alternatives(values):
    return '(?:' + '|'.join(re.escape(v) for v in sorted(values, key=lambda v: (-len(v), v))) + ')'


def generate():
    grammar = luthier_syntax()
    literals = set(lits_of(grammar))
    words = {v for v in literals if re.fullmatch(NAME, v)}
    # Read the existing value, rather than restating the precedence table.
    levels = json.loads(re.search(r'^precedenceLevels\s*:[^\n]*:=\s*(\[[^\n]*\])',
                                 GRAMMAR_LTH.read_text(), re.M)[1])
    operators = set(lits_of_names(grammar, levels))
    patterns = [
        {'name': 'comment.line.double-dash.luthier', 'match': '--.*$'},
        {'name': 'string.quoted.double.luthier', 'begin': '"', 'end': '"',
         'patterns': [
             {'name': 'constant.character.escape.luthier', 'match': r'\\["\\n]'},
             {'name': 'invalid.illegal.escape.luthier', 'match': r'\\.'}]},
    ]
    def add(scope, values, bounded=False):
        if values:
            match = alternatives(values)
            if bounded:
                match = '(?<!' + EDGE + ')' + match + '(?!' + EDGE + ')'
            patterns.append({'name': scope + '.luthier', 'match': match})
    add('keyword.control', words - operators, True)
    add('keyword.operator', words & operators, True)
    symbols = literals - words - operators - {'\n'}
    # Punctuation precedes operators (e.g. <- before <); guard prefixes such
    # as | so an operator such as || remains a single match.
    if symbols:
        choices = []
        for symbol in sorted(symbols, key=lambda v: (-len(v), v)):
            suffixes = {op[len(symbol):] for op in operators if op.startswith(symbol)}
            choices.append(re.escape(symbol) + ('(?!' + alternatives(suffixes) + ')' if suffixes else ''))
        patterns.append({'name': 'punctuation.luthier', 'match': '(?:' + '|'.join(choices) + ')'})
    add('keyword.operator', operators - words)
    if 'number' in cats_of(grammar):
        patterns.append({'name': 'constant.numeric.luthier',
                         'match': r"(?<![A-Za-z0-9_'.])[0-9]+(?:\.[0-9]+)?(?:[eE][+-]?[0-9]+)?"})
    if 'name' in cats_of(grammar):
        add('support.type', set(coreNames) - literals, True)
        patterns.append({'name': 'variable.other.luthier', 'match': NAME})
    digest = hashlib.sha256(GRAMMAR_LTH.read_bytes()).hexdigest()
    core_digest = hashlib.sha256((ROOT / 'src/luthier/check.py').read_bytes()).hexdigest()
    header = {'_generated': f'Generated by scripts/gen_grammar.py v1; grammar.lth sha256: {digest}; check.py sha256: {core_digest}; deterministic; no seed; no rendering parameters.'}
    # A header line within JSON keeps the grammar consumable by TextMate.
    body = {'name': 'Luthier', 'scopeName': 'source.luthier', 'patterns': patterns}
    return '{\n  ' + json.dumps('_generated') + ': ' + json.dumps(header['_generated']) + ',\n' + json.dumps(body, indent=2)[2:]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != expected:
            print(f'{OUTPUT}: stale; run python3 scripts/gen_grammar.py', file=sys.stderr)
            return 1
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(expected)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
